import assert from 'node:assert/strict';
import {ReplayTape} from '../replay.mjs';
const initial = {score: 3};
const tape = new ReplayTape({id: 'snake', seed: 17, initial, maxFrames: 2});
initial.score = 100;
assert.equal(tape.initial.score, 3);
const input = {down: a => a === 'left', pressed: a => a === 'fire', pointer: {x: 3, y: 8, down: true}};
tape.record(input);
input.pointer.x = 99;
let frame = tape.next();
assert.equal(frame.down('left'), true);
assert.equal(frame.pressed('fire'), true);
assert.equal(frame.pressed('confirm'), false);
assert.equal(frame.pointer.x, 3);
assert.equal(tape.next(), null);
tape.reset();
assert.equal(tape.next().pointer.x, 3);
tape.record(input);
tape.record(input);
assert.equal(tape.complete, false);
assert.equal(tape.frames.length, 2);
console.log('Replay tape tests passed');
